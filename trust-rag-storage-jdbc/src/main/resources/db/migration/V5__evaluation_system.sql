ALTER TABLE rag_trace ADD COLUMN trace_type VARCHAR(32) NOT NULL DEFAULT 'NORMAL';
ALTER TABLE rag_trace ADD COLUMN eval_run_id BIGINT;
ALTER TABLE rag_trace ADD COLUMN eval_case_id BIGINT;
CREATE INDEX idx_rag_trace_eval
    ON rag_trace(trace_type, eval_run_id, eval_case_id);

CREATE TABLE eval_dataset (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    description TEXT,
    tenant_id VARCHAR(64),
    project_id VARCHAR(64),
    created_by VARCHAR(64),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_eval_dataset_scope
    ON eval_dataset(tenant_id, project_id, enabled);

CREATE TABLE eval_case (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_id BIGINT NOT NULL,
    question TEXT NOT NULL,
    expected_answer TEXT,
    tenant_id VARCHAR(64),
    project_id VARCHAR(64),
    user_id VARCHAR(64),
    conversation_id VARCHAR(64),
    tags TEXT,
    difficulty VARCHAR(32),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_eval_case_dataset FOREIGN KEY (dataset_id) REFERENCES eval_dataset(id)
);

CREATE INDEX idx_eval_case_dataset
    ON eval_case(dataset_id, enabled, id);

CREATE TABLE eval_case_expected_knowledge (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    eval_case_id BIGINT NOT NULL,
    knowledge_id BIGINT NOT NULL,
    relevance_grade INT NOT NULL DEFAULT 1,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_eval_expected_case FOREIGN KEY (eval_case_id) REFERENCES eval_case(id),
    CONSTRAINT fk_eval_expected_knowledge FOREIGN KEY (knowledge_id) REFERENCES knowledge_item(id)
);

CREATE UNIQUE INDEX uk_eval_expected_case_knowledge
    ON eval_case_expected_knowledge(eval_case_id, knowledge_id);

CREATE TABLE eval_run (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_id BIGINT NOT NULL,
    run_name VARCHAR(255),
    run_type VARCHAR(32) NOT NULL,
    before_after_group VARCHAR(32) NOT NULL DEFAULT 'NORMAL',
    status VARCHAR(32) NOT NULL,
    total_count INT NOT NULL DEFAULT 0,
    success_count INT NOT NULL DEFAULT 0,
    failed_count INT NOT NULL DEFAULT 0,
    engine_config_snapshot TEXT,
    model_config_snapshot TEXT,
    knowledge_snapshot_time TIMESTAMP WITH TIME ZONE,
    started_at TIMESTAMP WITH TIME ZONE,
    finished_at TIMESTAMP WITH TIME ZONE,
    error_message TEXT,
    created_by VARCHAR(64),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_eval_run_dataset FOREIGN KEY (dataset_id) REFERENCES eval_dataset(id)
);

CREATE INDEX idx_eval_run_dataset
    ON eval_run(dataset_id, created_at);
CREATE INDEX idx_eval_run_status
    ON eval_run(status, created_at);

CREATE TABLE eval_result (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    eval_run_id BIGINT NOT NULL,
    eval_case_id BIGINT NOT NULL,
    trace_id VARCHAR(64),
    question TEXT NOT NULL,
    expected_answer TEXT,
    answer TEXT,
    retrieved_count INT NOT NULL DEFAULT 0,
    expected_knowledge_count INT NOT NULL DEFAULT 0,
    recall_at_5 NUMERIC(8,6),
    recall_at_10 NUMERIC(8,6),
    precision_at_5 NUMERIC(8,6),
    precision_at_10 NUMERIC(8,6),
    mrr NUMERIC(8,6),
    ndcg_at_5 NUMERIC(8,6),
    ndcg_at_10 NUMERIC(8,6),
    faithfulness NUMERIC(8,6),
    answer_correctness NUMERIC(8,6),
    answer_relevance NUMERIC(8,6),
    hallucination_score NUMERIC(8,6),
    prompt_tokens INT NOT NULL DEFAULT 0,
    completion_tokens INT NOT NULL DEFAULT 0,
    latency_ms BIGINT NOT NULL DEFAULT 0,
    status VARCHAR(32) NOT NULL,
    error_message TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_eval_result_run FOREIGN KEY (eval_run_id) REFERENCES eval_run(id),
    CONSTRAINT fk_eval_result_case FOREIGN KEY (eval_case_id) REFERENCES eval_case(id)
);

CREATE INDEX idx_eval_result_run
    ON eval_result(eval_run_id, eval_case_id);

CREATE TABLE eval_judge_detail (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    eval_result_id BIGINT NOT NULL,
    eval_run_id BIGINT NOT NULL,
    eval_case_id BIGINT NOT NULL,
    judge_type VARCHAR(64) NOT NULL,
    model VARCHAR(128),
    prompt TEXT,
    raw_output TEXT,
    score NUMERIC(8,6),
    passed BOOLEAN,
    reason TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_eval_judge_result FOREIGN KEY (eval_result_id) REFERENCES eval_result(id)
);

CREATE INDEX idx_eval_judge_result
    ON eval_judge_detail(eval_result_id, judge_type);

CREATE TABLE eval_report (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    eval_run_id BIGINT NOT NULL UNIQUE,
    dataset_id BIGINT NOT NULL,
    total_count INT NOT NULL DEFAULT 0,
    success_count INT NOT NULL DEFAULT 0,
    failed_count INT NOT NULL DEFAULT 0,
    avg_recall_at_5 NUMERIC(8,6),
    avg_recall_at_10 NUMERIC(8,6),
    avg_precision_at_5 NUMERIC(8,6),
    avg_precision_at_10 NUMERIC(8,6),
    avg_mrr NUMERIC(8,6),
    avg_ndcg_at_5 NUMERIC(8,6),
    avg_ndcg_at_10 NUMERIC(8,6),
    avg_faithfulness NUMERIC(8,6),
    avg_answer_correctness NUMERIC(8,6),
    avg_answer_relevance NUMERIC(8,6),
    avg_hallucination_score NUMERIC(8,6),
    avg_latency_ms NUMERIC(12,3),
    p90_latency_ms NUMERIC(12,3),
    summary_json TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_eval_report_run FOREIGN KEY (eval_run_id) REFERENCES eval_run(id)
);

CREATE TABLE eval_compare_report (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    before_run_id BIGINT NOT NULL,
    after_run_id BIGINT NOT NULL,
    recall_at_10_delta NUMERIC(8,6),
    mrr_delta NUMERIC(8,6),
    faithfulness_delta NUMERIC(8,6),
    answer_correctness_delta NUMERIC(8,6),
    hallucination_score_delta NUMERIC(8,6),
    conclusion TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE eval_governance_snapshot (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id VARCHAR(64),
    project_id VARCHAR(64),
    snapshot_date DATE NOT NULL,
    total_candidate_count BIGINT NOT NULL DEFAULT 0,
    approved_candidate_count BIGINT NOT NULL DEFAULT 0,
    rejected_candidate_count BIGINT NOT NULL DEFAULT 0,
    candidate_approval_rate NUMERIC(8,6),
    knowledge_reuse_rate NUMERIC(8,6),
    contamination_rate NUMERIC(8,6),
    privacy_leakage_rate NUMERIC(8,6),
    gap_resolve_rate NUMERIC(8,6),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_eval_governance_scope_date
    ON eval_governance_snapshot(tenant_id, project_id, snapshot_date);

CREATE TABLE privacy_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trace_id VARCHAR(64),
    knowledge_id BIGINT,
    tenant_id VARCHAR(64),
    project_id VARCHAR(64),
    event_type VARCHAR(64) NOT NULL,
    risk_level VARCHAR(32),
    description TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_privacy_event_scope_time
    ON privacy_event(tenant_id, project_id, created_at);
